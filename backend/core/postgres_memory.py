"""Reuse MemoryManager's domain operations with a bounded PostgreSQL SQL adapter.

Only the SQL dialect used by memory.py is supported; this is not a general SQLite
emulator. Each statement autocommits, so unrelated coroutines cannot accidentally
commit or roll back each other's work. Blocking driver calls run off the event loop
(including on Windows' default Proactor loop).
"""
import asyncio
import re
import threading

from .memory import MemoryManager


def postgres_sql(statement):
    statement = statement.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    statement = re.sub(r"\bINTEGER\b", "BIGINT", statement)
    if "INSERT OR IGNORE" in statement:
        statement = statement.replace("INSERT OR IGNORE", "INSERT") + " ON CONFLICT DO NOTHING"
    # memory.py's placeholders never appear inside string literals.
    statement = statement.replace("?", "%s")
    if re.match(r"\s*INSERT INTO (pending_replies|chat_history)\b", statement):
        statement += " RETURNING id"
    return statement


class Row(dict):
    def __getitem__(self, key):
        return list(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


class Result:
    def __init__(self, rows=(), rowcount=0, lastrowid=None):
        self.rows = list(rows)
        self.rowcount = rowcount
        self.lastrowid = lastrowid

    async def fetchall(self):
        rows, self.rows = self.rows, []
        return rows

    async def fetchone(self):
        return self.rows.pop(0) if self.rows else None

    async def close(self):
        pass


class Query:
    def __init__(self, connection, statement, params):
        self.connection, self.statement, self.params = connection, statement, params

    def __await__(self):
        return asyncio.to_thread(self.connection.run, self.statement, self.params).__await__()

    async def __aenter__(self):
        return await self

    async def __aexit__(self, *args):
        pass


class Connection:
    def __init__(self, connection):
        self.connection = connection
        self.lock = threading.RLock()

    def execute(self, statement, params=()):
        return Query(self, statement, params)

    async def executemany(self, statement, parameters):
        for params in parameters:
            await self.execute(statement, params)

    def run(self, statement, params):
        if statement.startswith("PRAGMA"):
            return Result()
        sql = postgres_sql(statement)
        with self.lock, self.connection.cursor() as cursor:
            cursor.execute(sql, params)
            rows = [Row(zip((col.name for col in cursor.description), row)) for row in cursor.fetchall()] if cursor.description else []
            last_id = rows[0][0] if " RETURNING id" in sql and rows else None
            return Result(rows, cursor.rowcount, last_id)

    async def commit(self):
        pass  # autocommit; never create cross-coroutine transactions

    async def close(self):
        await asyncio.to_thread(self.connection.close)


class PostgresMemoryManager(MemoryManager):
    def __init__(self, url, **kwargs):
        super().__init__(**kwargs)
        self._url = url
        self.db_path = "postgresql"  # safe diagnostic label, not a DSN or local path

    async def _get_db(self):
        if self._conn:
            return self._conn
        async with self._init_lock:
            if not self._conn:
                import psycopg
                raw = await asyncio.to_thread(psycopg.connect, self._url, autocommit=True, connect_timeout=10)
                self._conn = Connection(raw)
                try:
                    await self._init_tables()
                except BaseException:
                    await self._conn.close()
                    self._conn = None
                    raise
        return self._conn

    async def _ensure_column(self, table, column, definition):
        # All identifiers and definitions are constants in MemoryManager._init_tables.
        await self._conn.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} {definition}")
