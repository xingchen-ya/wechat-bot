import sqlite3

import pytest

from backend.core.storage import create_memory, database_url
from backend.core.memory import MemoryManager
from backend.core.postgres_memory import postgres_sql, Row
from backend.core.postgres_vectors import PostgresVectorMemory
from scripts.migrate_postgres import migrate, open_source, source_tables


def test_selection_is_explicit_and_secrets_stay_out_of_paths(monkeypatch):
    monkeypatch.setenv("WECHAT_BOT_DATABASE_URL", "postgresql://example.invalid/test")
    assert type(create_memory({})) is MemoryManager
    pg = create_memory({"storage_backend": "postgres"})
    assert pg.db_path == "postgresql"
    monkeypatch.delenv("WECHAT_BOT_DATABASE_URL")
    with pytest.raises(ValueError):
        database_url({"storage_backend": "postgres"})


def test_memory_sql_dialect_preserves_values_and_generated_ids():
    assert "ON CONFLICT DO NOTHING" in postgres_sql("INSERT OR IGNORE INTO user_profiles (wx_id,updated_at) VALUES (?,?)")
    assert postgres_sql("INSERT INTO pending_replies (chat_id) VALUES (?)").endswith("RETURNING id")
    assert "GENERATED BY DEFAULT AS IDENTITY" in postgres_sql("id INTEGER PRIMARY KEY AUTOINCREMENT")
    row = Row(zip(["name", "count"], ["contact", 2]))
    assert row[0] == row["name"] == "contact"


def test_pg_embedding_validation_without_connection():
    vectors = object.__new__(PostgresVectorMemory)
    vectors.dimensions = 2
    assert vectors._embedding([1, 2]) == "[1.0, 2.0]"
    for values in ([1], [0, 0], [float("nan"), 1], [float("inf"), 1]):
        with pytest.raises(ValueError):
            vectors._embedding(values)


@pytest.mark.asyncio
async def test_dry_run_is_offline_and_read_only(tmp_path, monkeypatch):
    path = tmp_path / "memory.db"
    memory = MemoryManager(str(path))
    await memory.add_message("synthetic", "user", "offline test")
    await memory.close()
    original = path.read_bytes()
    monkeypatch.delenv("WECHAT_BOT_DATABASE_URL", raising=False)
    assert migrate(path)["source_counts"]["chat_history"] == 1
    assert path.read_bytes() == original
    with open_source(path) as source:
        with pytest.raises(sqlite3.OperationalError):
            source.execute("DELETE FROM chat_history")


def test_unknown_tables_refused(tmp_path):
    with sqlite3.connect(tmp_path / "unknown.db") as source:
        source.execute("CREATE TABLE custom_data(id INTEGER)")
        with pytest.raises(ValueError):
            source_tables(source, ("chat_history",))


def test_postgres_file_maintenance_is_blocked(tmp_path):
    from backend.core.workspace_backup import WorkspaceBackupService
    from backend.core.data_controls import DataControlService
    config = {"storage_backend": "postgres"}
    backup = WorkspaceBackupService(data_root=tmp_path, bot_config=config)
    with pytest.raises(ValueError, match="pg_dump"):
        backup.create_backup("full")
    with pytest.raises(ValueError, match="pg_restore"):
        backup.build_restore_plan("anything")
    with pytest.raises(ValueError, match="PostgreSQL"):
        DataControlService(data_root=tmp_path, bot_config=config).clear(["memory"])
